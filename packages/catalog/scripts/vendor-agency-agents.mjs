// Vendors the `engineering/` agents of agency-agents (MIT) at one commit as ready-made roles.
// Run by hand, never in CI or tests:
//   node packages/catalog/scripts/vendor-agency-agents.mjs <full commit sha>
// It rewrites src/roles/presets/agency-agents.ts and LICENSE-agency-agents; review the diff, and
// re-read the missions of the new or changed presets before touching `READ_ONLY_PRESETS`.
import { writeFileSync } from 'node:fs'

const REPOSITORY = 'msitarzewski/agency-agents'
const FOLDER = 'engineering/'
const PREFIX = 'engineering-'
const OUT = new URL('../src/roles/presets/', import.meta.url)

const sha = process.argv[2] ?? ''
if (!/^[0-9a-f]{40}$/.test(sha)) {
  console.error('Usage: node vendor-agency-agents.mjs <full 40-character commit sha>')
  process.exit(1)
}

async function get(url) {
  const response = await fetch(url, { headers: { 'User-Agent': 'vendor-agency-agents' } })
  if (!response.ok) throw new Error(`${response.status} for ${url}`)
  return response
}

const raw = async (path) =>
  (await (await get(`https://raw.githubusercontent.com/${REPOSITORY}/${sha}/${path}`)).text())
    .replace(/^\uFEFF/, '')
    .replaceAll('\r\n', '\n')

const oneLine = (text) => text.replace(/\s+/g, ' ').trim()

/** The top-level scalars of a frontmatter block; a value may continue on indented lines. */
function frontmatter(block) {
  const fields = {}
  let key = null
  for (const row of block.split('\n')) {
    const match = /^([A-Za-z_][\w-]*):(.*)$/.exec(row)
    if (match) {
      key = match[1]
      fields[key] = match[2].trim().replace(/^[>|][+-]?$/, '')
    } else if (key && /^\s+\S/.test(row)) {
      fields[key] += ` ${row.trim()}`
    }
  }
  for (const [name, value] of Object.entries(fields)) {
    const folded = oneLine(value)
    const quoted = /^(["'])(.*)\1$/.exec(folded)
    if (!quoted) fields[name] = folded
    else if (quoted[1] === '"') fields[name] = JSON.parse(folded)
    else fields[name] = quoted[2].replaceAll("''", "'")
  }
  return fields
}

/** A string literal the way the formatter writes it: single quotes unless that costs more escapes. */
function literal(text) {
  const quote = text.split("'").length > text.split('"').length ? '"' : "'"
  return quote + text.replaceAll('\\', '\\\\').replaceAll(quote, `\\${quote}`) + quote
}

/** A property on one line, or with its value on the next when the line passes the formatter's width. */
function property(key, value) {
  const row = `    ${key}: ${value},`
  return row.length <= 100 ? row : `    ${key}:\n      ${value},`
}

const template = (text) =>
  `\`${text.replaceAll('\\', '\\\\').replaceAll('`', '\\`').replaceAll('${', '\\${')}\``

const tree = await (
  await get(`https://api.github.com/repos/${REPOSITORY}/git/trees/${sha}?recursive=1`)
).json()
if (tree.truncated) throw new Error('The tree listing is truncated')

const paths = tree.tree
  .filter((entry) => entry.type === 'blob')
  .map((entry) => entry.path)
  .filter((path) => path.startsWith(FOLDER) && path.endsWith('.md'))
  .filter((path) => !path.slice(FOLDER.length).includes('/'))
if (paths.length === 0) throw new Error(`No file under ${FOLDER}`)

const presets = []
for (const path of paths) {
  const file = path.slice(FOLDER.length, -'.md'.length)
  const slug = file.startsWith(PREFIX) ? file.slice(PREFIX.length) : file
  const match = /^---\n([\s\S]*?)\n---\n([\s\S]*)$/.exec(await raw(path))
  if (!match) throw new Error(`${path}: no frontmatter`)
  const { name, description } = frontmatter(match[1])
  const mission = match[2].trim()
  if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(slug)) throw new Error(`${path}: slug ${slug}`)
  if (!name || !description || !mission) throw new Error(`${path}: a field is empty`)
  presets.push({ slug, name, description, mission })
}
presets.sort((a, b) => (a.slug < b.slug ? -1 : a.slug > b.slug ? 1 : 0))
for (const [index, preset] of presets.entries()) {
  if (preset.slug === presets[index - 1]?.slug) throw new Error(`Duplicate slug ${preset.slug}`)
}

const entries = presets.map(
  (preset) => `  {
${property('slug', literal(preset.slug))}
${property('name', literal(preset.name))}
${property('description', literal(preset.description))}
    mission: ${template(preset.mission)},
  },
`,
)

writeFileSync(
  new URL('agency-agents.ts', OUT),
  `// Generated by scripts/vendor-agency-agents.mjs: do not edit by hand, run the script again.
// Source: https://github.com/${REPOSITORY}, folder \`${FOLDER}\`
// Commit: ${sha}
// Licence: MIT, see LICENSE-agency-agents next to this file.

export const AGENCY_AGENTS_REPOSITORY = 'https://github.com/${REPOSITORY}'

export const AGENCY_AGENTS_COMMIT = '${sha}'

/** How many \`${FOLDER}*.md\` files the repository holds at that commit. */
export const AGENCY_AGENTS_FILE_COUNT = ${paths.length}

/** A ready-made role: what the source file says, without rights. */
export type RolePreset = { slug: string; name: string; description: string; mission: string }

/** Sorted by slug. */
export const ROLE_PRESETS: readonly RolePreset[] = [
${entries.join('')}]
`,
)
writeFileSync(new URL('LICENSE-agency-agents', OUT), await raw('LICENSE'))

const longest = (field) => Math.max(...presets.map((preset) => preset[field].length))
console.log(
  `${presets.length} presets at ${sha}; longest name ${longest('name')}, ` +
    `description ${longest('description')}, mission ${longest('mission')}`,
)
